#!/usr/bin/env node
// Writes src/generated/routes.ts from cauthy-sdk-spec's protocol/routes.yaml:
// every route of the auth-bff protocol with its method, path, needs, answer
// fields, and the TypeScript type of its body and query. The client's calls
// are typed against it, so a route the spec changes fails the typecheck here.
//
//   SPEC_DIR=../cauthy-sdk-spec npm run gen:routes      # writes the file
//   node scripts/gen-routes.mjs /tmp/routes.ts          # writes elsewhere (check-routes.sh)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const spec = resolve(process.env.SPEC_DIR ?? resolve(root, '../cauthy-sdk-spec'))
const out = resolve(process.argv[2] ?? resolve(root, 'src/generated/routes.ts'))

const table = parse(readFileSync(resolve(spec, 'protocol/routes.yaml'), 'utf8'))
const version = Number(readFileSync(resolve(spec, 'VERSION'), 'utf8').trim())
if (table.version !== version) throw new Error(`routes.yaml says version ${table.version}; VERSION says ${version}`)

const TS = { string: 'string', email: 'string', uuid: 'string', number: 'number', boolean: 'boolean', object: 'Record<string, unknown>', array: 'unknown[]' }
const ts = (type, where) => {
  if (!(type in TS)) throw new Error(`${where}: unknown type ${type}`)
  return TS[type]
}
const q = (v) => JSON.stringify(v)
const shape = (params, where) => {
  const entries = Object.entries(params ?? {})
  if (entries.length === 0) return 'Record<string, never>'
  return `{ ${entries.map(([name, p]) => `${q(name)}${p.required ? '' : '?'}: ${ts(p.type, `${where}.${name}`)}`).join('; ')} }`
}

const seen = new Set()
const rows = []
const bodies = []
const queries = []
for (const r of table.routes) {
  if (seen.has(r.id)) throw new Error(`route ${r.id} appears twice`)
  seen.add(r.id)
  const fields = Object.fromEntries(Object.entries(r.success?.fields ?? {}).map(([k, v]) => [k, String(v)]))
  rows.push(`  ${q(r.id)}: { method: ${q(r.method)}, path: ${q(r.path)}, group: ${q(r.group)}, level: ${q(r.level)}, needs: ${q(r.needs ?? [])}, redirect: ${r.success?.redirect === true}, stream: ${r.stream === true}, deprecated: ${r.deprecated === true}, fields: ${q(fields)} },`)
  if (r.method === 'POST') bodies.push(`  ${q(r.id)}: ${shape(r.body, r.id)}`)
  queries.push(`  ${q(r.id)}: ${shape(r.query, r.id)}`)
}

const text = `// GENERATED by scripts/gen-routes.mjs from cauthy-sdk-spec protocol/routes.yaml
// at the commit spec.lock pins. Do not edit: run \`npm run gen:routes\`.

/** The auth-bff protocol version these routes are. */
export const PROTOCOL = ${version} as const
/** Where a backend mounts the routes unless told otherwise. */
export const PREFIX = ${q(table.prefix)} as const

export interface RouteInfo {
  readonly method: 'GET' | 'POST'
  readonly path: string
  readonly group: 'hosted' | 'session' | 'sign-in' | 'me' | 'organizations' | 'other'
  readonly level: 'basic' | 'strict'
  readonly needs: readonly ('session' | 'tenant' | 'step' | 'crosssite' | 'json')[]
  readonly redirect: boolean
  readonly stream: boolean
  readonly deprecated: boolean
  /** The answer's fields and their types; a type ending in \`?\` may be absent or null. */
  readonly fields: Readonly<Record<string, string>>
}

export const ROUTES = {
${rows.join('\n')}
} as const satisfies Record<string, RouteInfo>

export type RouteId = keyof typeof ROUTES
export type PostRouteId = { [K in RouteId]: (typeof ROUTES)[K]['method'] extends 'POST' ? K : never }[RouteId]
export type GetRouteId = Exclude<RouteId, PostRouteId>

/** What each POST route takes as its JSON body. */
export interface RouteBodies {
${bodies.join('\n')}
}

/** What each route takes as its query. */
export interface RouteQueries {
${queries.join('\n')}
}
`
writeFileSync(out, text)
console.log(`${table.routes.length} routes of auth-bff version ${version} -> ${out}`)
